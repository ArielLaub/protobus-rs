//! Services: a named queue of requests, the handlers that answer them, and the
//! events the service subscribes to.

use std::collections::{HashMap, HashSet};
use std::future::Future;
use std::sync::{Arc, Mutex, RwLock};

use prost::Message;
use prost_reflect::{DynamicMessage, ReflectMessage};
use tokio::sync::mpsc;

use crate::amqp::{BoxFuture, FieldTable};
use crate::connection::{CancelToken, HandlerFailure, HandlerResult, MessageHandler, MessageHandlerContext};
use crate::context::Context;
use crate::errors::{sanitize_error_for_client, Error, ErrorKind, Result};
use crate::listeners::{CancelListener, EventInfo, EventListener, MessageListener};
use crate::message_dispatcher::SERIALIZED_SERVICE;
use crate::message_factory::MessageFactory;
use crate::options::MessageServiceOptions;
use crate::stream::{RawStreamWriter, StreamWriter};
use crate::wire;

/// What a service handler receives besides its request.
#[derive(Clone, Debug)]
pub struct CallContext {
    /// Free-text caller identity from the request envelope; empty when none.
    /// Not authenticated.
    pub actor: String,
    pub correlation_id: String,
    /// The contract method, `<package>.<Service>.<method>`.
    pub method: String,
    /// Fires on the processing timeout and, for a stream, when the caller
    /// cancels. Watch it in long or cancellable work: nothing else stops a
    /// handler.
    pub cancel: CancelToken,
    /// The routing key the broker delivered on.
    pub routing_key: String,
    /// Stable across redeliveries and retries: deduplicate on it. `None` if
    /// the publisher set none.
    pub message_id: Option<String>,
    pub redelivered: bool,
    pub headers: Arc<FieldTable>,
}

type UnaryMethod = Arc<dyn Fn(Vec<u8>, CallContext) -> BoxFuture<'static, Result<Vec<u8>>> + Send + Sync>;
type StreamMethod = Arc<dyn Fn(Vec<u8>, CallContext, RawStreamWriter) -> BoxFuture<'static, Result<()>> + Send + Sync>;

#[derive(Clone)]
enum MethodEntry {
    Unary(UnaryMethod),
    Stream(StreamMethod),
}

struct Contract {
    service_name: String,
    methods: HashSet<String>,
}

struct Inner {
    context: Context,
    service_name: String,
    options: MessageServiceOptions,
    listener: MessageListener,
    event_listener: EventListener,
    cancel_listener: CancelListener,
    methods: RwLock<HashMap<String, MethodEntry>>,
    /// The service as its .proto declares it, which is not always the service
    /// name: instances sharing one schema are addressed under distinct runtime
    /// names (`Combat.Player.player6` serving the contract `Combat.Player`).
    contract: RwLock<Option<Arc<Contract>>>,
    schemas: Mutex<Vec<&'static [u8]>>,
    /// Held by every handler when `serialize_handlers` is on.
    turn: Option<Arc<tokio::sync::Mutex<()>>>,
}

/// A service on the bus.
///
/// It is named by its service name, normally its .proto `<package>.<Service>`.
/// It owns one durable queue of that name, bound to `REQUEST.<name>.*`, which
/// every replica consumes from, so the broker balances load and fails over. It
/// also owns `<name>.Events` for the events it subscribes to.
///
/// Code generated by `protobus-build` gives each proto service a handler trait
/// and a `<Service>Service::new(&ctx, handler)` that builds one of these with
/// a method registered per rpc. Without codegen, build one directly and
/// register handlers over dynamic messages with
/// [`register_method`](Self::register_method).
///
/// A handler's error decides what happens to the request. A
/// [handled](Error::handled) error is an answer: it reaches the caller with
/// its code and is never retried. Anything else, or a processing timeout, is a
/// failure: the request is retried through the service's retry queue and
/// dead-lettered once retries are spent, and the caller is answered then.
///
/// Handlers run in parallel, on the runtime's worker threads, up to
/// `max_concurrent`; they are `Send + Sync`, so the compiler already holds
/// their shared state to that. Cheap to clone: every clone is the same service.
#[derive(Clone)]
pub struct MessageService {
    inner: Arc<Inner>,
}

impl MessageService {
    /// A service named `service_name`. Several instances can share one schema
    /// under distinct names: the contract is found by trimming trailing
    /// segments until one names a known service.
    pub fn new(context: &Context, service_name: impl Into<String>, options: MessageServiceOptions) -> Result<Self> {
        let connection = context.connection();
        let listener = MessageListener::new(
            connection,
            options.late_ack,
            options.max_concurrent,
            Some(options.retry.clone()),
            options.processing_timeout_ms,
            options.max_priority,
        )?;
        listener.set_build_error_reply(Arc::new(build_failure_reply));
        Ok(MessageService {
            inner: Arc::new(Inner {
                context: context.clone(),
                service_name: service_name.into(),
                event_listener: EventListener::new(connection, context.factory(), Some(options.event_retry.clone())),
                cancel_listener: CancelListener::new(connection),
                turn: options
                    .serialize_handlers
                    .then(|| Arc::new(tokio::sync::Mutex::new(()))),
                options,
                listener,
                methods: RwLock::new(HashMap::new()),
                contract: RwLock::new(None),
                schemas: Mutex::new(Vec::new()),
            }),
        })
    }

    /// The service's name on the bus.
    pub fn service_name(&self) -> &str {
        &self.inner.service_name
    }

    pub fn options(&self) -> &MessageServiceOptions {
        &self.inner.options
    }

    pub fn context(&self) -> &Context {
        &self.inner.context
    }

    /// The contract this service serves, once [`init`](Self::init) has resolved it.
    pub fn contract_service_name(&self) -> Option<String> {
        self.inner
            .contract
            .read()
            .unwrap()
            .as_ref()
            .map(|c| c.service_name.clone())
    }

    /// A compiled descriptor set declaring the service, registered on init.
    /// Generated code passes the one compiled into the program.
    pub fn with_schema(self, descriptor_set: &'static [u8]) -> Self {
        self.inner.schemas.lock().unwrap().push(descriptor_set);
        self
    }

    // ---- registration ------------------------------------------------------------

    fn add(&self, name: &str, entry: MethodEntry) {
        self.inner.methods.write().unwrap().insert(name.to_string(), entry);
    }

    /// Register a typed unary handler, as generated code does.
    pub fn register_unary<Req, Res, F, Fut>(&self, name: &str, handler: F)
    where
        Req: Message + prost::Name + Default + 'static,
        Res: Message + prost::Name + 'static,
        F: Fn(Req, CallContext) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<Res>> + Send + 'static,
    {
        let factory = self.inner.context.factory().clone();
        self.add(
            name,
            MethodEntry::Unary(Arc::new(move |payload, call| {
                let request = decode_request::<Req>(&factory, &payload, &call.method);
                // The handler's future is created only for a request that decoded.
                let work = request.map(|request| handler(request, call));
                let factory = factory.clone();
                Box::pin(async move { factory.encode(&work?.await?) })
            })),
        );
    }

    /// Register a typed server-streaming handler, as generated code does.
    pub fn register_stream<Req, Res, F, Fut>(&self, name: &str, handler: F)
    where
        Req: Message + prost::Name + Default + 'static,
        Res: Message + prost::Name + 'static,
        F: Fn(Req, CallContext, StreamWriter<Res>) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<()>> + Send + 'static,
    {
        let factory = self.inner.context.factory().clone();
        self.add(
            name,
            MethodEntry::Stream(Arc::new(move |payload, call, raw| {
                let encoder = factory.clone();
                let writer = StreamWriter::new(raw, Arc::new(move |chunk: &Res| encoder.encode(chunk)));
                let work = decode_request::<Req>(&factory, &payload, &call.method)
                    .map(|request| handler(request, call, writer));
                Box::pin(async move { work?.await })
            })),
        );
    }

    /// Register a unary handler over dynamic messages: the request is a
    /// dynamic message of the contract's request type, and the result must be
    /// of its response type.
    pub fn register_method<F, Fut>(&self, name: &str, handler: F)
    where
        F: Fn(DynamicMessage, CallContext) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<DynamicMessage>> + Send + 'static,
    {
        let factory = self.inner.context.factory().clone();
        self.add(
            name,
            MethodEntry::Unary(Arc::new(move |payload, call| {
                let method = call.method.clone();
                let work = decode_dynamic_request(&factory, &payload, &method).map(|request| handler(request, call));
                let factory = factory.clone();
                Box::pin(async move { encode_dynamic_result(&factory, &method, &work?.await?) })
            })),
        );
    }

    /// A server-streaming handler over dynamic messages; see
    /// [`register_method`](Self::register_method).
    pub fn register_streaming_method<F, Fut>(&self, name: &str, handler: F)
    where
        F: Fn(DynamicMessage, CallContext, StreamWriter<DynamicMessage>) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<()>> + Send + 'static,
    {
        let factory = self.inner.context.factory().clone();
        self.add(
            name,
            MethodEntry::Stream(Arc::new(move |payload, call, raw| {
                let method = call.method.clone();
                let encoder = factory.clone();
                let encoded_for = method.clone();
                let writer = StreamWriter::new(
                    raw,
                    Arc::new(move |chunk: &DynamicMessage| encode_dynamic_result(&encoder, &encoded_for, chunk)),
                );
                let work =
                    decode_dynamic_request(&factory, &payload, &method).map(|request| handler(request, call, writer));
                Box::pin(async move { work?.await })
            })),
        );
    }

    // ---- lifecycle ---------------------------------------------------------------

    fn resolve_contract(&self) -> Result<Arc<Contract>> {
        if let Some(contract) = self.inner.contract.read().unwrap().clone() {
            return Ok(contract);
        }
        let factory = self.inner.context.factory();
        let name = &self.inner.service_name;
        let mut candidate = name.as_str();
        loop {
            if factory.has_service(candidate) {
                let contract = Arc::new(Contract {
                    service_name: candidate.to_string(),
                    methods: factory.service_method_names(candidate)?.into_iter().collect(),
                });
                *self.inner.contract.write().unwrap() = Some(contract.clone());
                return Ok(contract);
            }
            match candidate.rfind('.') {
                Some(cut) if cut > 0 => candidate = &candidate[..cut],
                _ => {
                    return Err(Error::new(
                        ErrorKind::MissingProto,
                        format!(
                            "no service in the schema matches '{name}' or any prefix of it; the schema must declare \
                             the service this class serves"
                        ),
                    ))
                }
            }
        }
    }

    /// Register the schema if needed, declare the queues and start consuming.
    pub async fn init(&self) -> Result<()> {
        let started = self.start().await;
        if let Err(e) = &started {
            log::error!(target: "protobus", "error initializing service {} - {e}", self.inner.service_name);
            self.close_quietly().await;
        }
        started
    }

    async fn start(&self) -> Result<()> {
        let inner = &self.inner;
        let schemas: Vec<&'static [u8]> = inner.schemas.lock().unwrap().clone();
        for schema in schemas {
            inner.context.factory().register_descriptor_set(schema)?;
        }
        self.resolve_contract()?;
        let name = &inner.service_name;
        inner.listener.init(Some(self.message_handler()), Some(name)).await?;
        inner.event_listener.init(Some(&format!("{name}.Events"))).await?;
        inner.listener.subscribe(&[&format!("REQUEST.{name}.*")]).await?;
        inner.listener.start().await?;
        inner.event_listener.start().await?;
        // Started last: it only matters once requests can arrive.
        inner.cancel_listener.start().await;
        Ok(())
    }

    /// Stop accepting new requests and events, leaving channels open so work
    /// in hand can finish: the first step of a graceful shutdown. Pair it with
    /// [`Connection::drain_in_flight`](crate::Connection::drain_in_flight)
    /// before closing anything.
    pub async fn stop_consuming(&self) {
        self.inner.listener.stop_consuming().await;
        self.inner.event_listener.stop_consuming().await;
        // A drained service has no stream left to cancel.
        self.inner.cancel_listener.close().await;
    }

    /// Stop consuming and close the service's channels.
    pub async fn close(&self) {
        self.stop_consuming().await;
        self.close_quietly().await;
    }

    async fn close_quietly(&self) {
        self.inner.listener.close().await;
        self.inner.event_listener.close().await;
        self.inner.cancel_listener.close().await;
    }

    // ---- events ------------------------------------------------------------------

    /// Publish an event of the message's own type, on `EVENT.<type>` unless a
    /// topic is given.
    pub async fn publish_event<T: Message + prost::Name>(&self, event: &T, topic: Option<&str>) -> Result<()> {
        self.inner.context.publish_event(event, topic).await
    }

    /// Subscribe this service to events of `T`, on `EVENT.<type>` or a topic
    /// or pattern of your choosing. Call after [`init`](Self::init). A handler
    /// that fails loses the event, unless event retry is on.
    pub async fn subscribe_event<T, F, Fut>(&self, handler: F, topic: Option<&str>) -> Result<()>
    where
        T: Message + prost::Name + Default + 'static,
        F: Fn(T, EventInfo) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<()>> + Send + 'static,
    {
        let turn = self.inner.turn.clone();
        let name = self.inner.service_name.clone();
        self.inner
            .event_listener
            .subscribe::<T, _, _>(
                move |event, info| in_turn(turn.clone(), name.clone(), handler(event, info)),
                topic,
            )
            .await
    }

    /// Subscribe to events of a type the factory knows by name, as dynamic messages.
    pub async fn subscribe_dynamic_event<F, Fut>(&self, type_name: &str, handler: F, topic: Option<&str>) -> Result<()>
    where
        F: Fn(DynamicMessage, EventInfo) -> Fut + Send + Sync + 'static,
        Fut: Future<Output = Result<()>> + Send + 'static,
    {
        let turn = self.inner.turn.clone();
        let name = self.inner.service_name.clone();
        self.inner
            .event_listener
            .subscribe_dynamic(
                type_name,
                move |event, info| in_turn(turn.clone(), name.clone(), handler(event, info)),
                topic,
            )
            .await
    }

    /// The service's event listener, for its retry topology.
    pub fn event_listener(&self) -> &EventListener {
        &self.inner.event_listener
    }

    // ---- dispatch ----------------------------------------------------------------

    fn message_handler(&self) -> MessageHandler {
        // Weak: the listener holds this handler, and the service holds the listener.
        let weak = Arc::downgrade(&self.inner);
        Arc::new(move |data, id, delivery| {
            let service = weak.upgrade().map(|inner| MessageService { inner });
            Box::pin(async move {
                match service {
                    Some(service) => service.on_message(data, id, delivery).await,
                    None => Err(Error::failure("the service was dropped").into()),
                }
            })
        })
    }

    /// The core handler for requests made to `REQUEST.<service name>.*`.
    async fn on_message(
        &self,
        data: Vec<u8>,
        id: String,
        delivery: MessageHandlerContext,
    ) -> std::result::Result<HandlerResult, HandlerFailure> {
        let inner = &self.inner;
        let service_name = &inner.service_name;
        let contract = self.resolve_contract()?;
        let routing_key = &delivery.routing_key;

        // Envelope first, payload later: the envelope names the method, and
        // that name selects the schema the payload is read with, so it is
        // checked against this service's contract before the bytes are
        // interpreted.
        let envelope = match wire::decode_request(&data) {
            Ok(e) => e,
            Err(_) => {
                log::error!(target: "protobus", "unparseable request envelope on {service_name} ({} bytes, {id})", data.len());
                let label = if routing_key.is_empty() { "unknown" } else { routing_key };
                return Ok(error_reply(label, &Error::protocol("request envelope did not decode")));
            }
        };
        log::debug!(target: "protobus", "received request {} ({id})", envelope.method);

        // A rejection is reported against the method the ROUTING KEY names: the
        // body's name is exactly what is in dispute.
        let named = if routing_key.is_empty() {
            last_segment(&envelope.method)
        } else {
            last_segment(routing_key)
        };
        let contract_method = format!("{}.{named}", contract.service_name);
        let reject = |reason: String| {
            log::error!(target: "protobus", "{reason}");
            Ok(error_reply(&contract_method, &Error::invalid_method(reason)))
        };

        // 1. The delivery belongs to THIS service, by the key the broker used.
        // 2. The body asks for the method the routing key names, so a client
        //    that can publish cannot route to one method and have another executed.
        if !routing_key.is_empty() {
            if !routing_key.starts_with(&format!("REQUEST.{service_name}.")) {
                return reject(format!(
                    "routing key {routing_key} does not belong to service {service_name}"
                ));
            }
            if last_segment(routing_key) != last_segment(&envelope.method) {
                return reject(format!(
                    "request method {} contradicts routing key {routing_key}",
                    envelope.method
                ));
            }
        }
        // 3. The body names a method of THIS contract, spelled in full.
        let method = match MessageFactory::split_method_name(&envelope.method) {
            Ok((service, method)) if service == contract.service_name => method.to_string(),
            Ok(_) => {
                return reject(format!(
                    "request method {} is not a method of {}",
                    envelope.method, contract.service_name
                ))
            }
            Err(_) => {
                return reject(format!(
                    "request method {} is not a qualified method name",
                    envelope.method
                ))
            }
        };
        if !contract.methods.contains(&method) {
            return reject(format!("{} declares no method {method}", contract.service_name));
        }

        let full_method = envelope.method;
        let entry = inner.methods.read().unwrap().get(&method).cloned();
        let Some(entry) = entry else {
            let error = Error::invalid_method(format!("invalid service method {method}"));
            log::error!(target: "protobus", "{error}");
            return Ok(error_reply(&full_method, &error));
        };
        let declared_streaming = inner.context.factory().is_streaming_method(&full_method);
        if matches!(entry, MethodEntry::Stream(_)) != declared_streaming {
            let error = Error::invalid_method(format!(
                "method {method} is registered as {} but declared otherwise",
                if declared_streaming { "unary" } else { "streaming" }
            ));
            log::error!(target: "protobus", "{error}");
            return Ok(error_reply(&full_method, &error));
        }

        let call = CallContext {
            actor: envelope.actor.unwrap_or_default(),
            correlation_id: id.clone(),
            method: full_method.clone(),
            cancel: delivery.cancel.clone(),
            routing_key: delivery.routing_key.clone(),
            message_id: delivery.message_id.clone(),
            redelivered: delivery.redelivered,
            headers: delivery.headers.clone(),
        };
        let turn = inner.turn.clone();
        match entry {
            MethodEntry::Unary(handler) => {
                let result = in_turn(turn, service_name.clone(), handler(envelope.data, call)).await;
                match result {
                    Ok(payload) => {
                        log::debug!(target: "protobus", "sending result {full_method} ({id})");
                        Ok(HandlerResult::Reply(MessageFactory::build_encoded_response(
                            &full_method,
                            payload,
                        )))
                    }
                    Err(error) => handle_unary_error(&full_method, error, &id),
                }
            }
            MethodEntry::Stream(handler) => {
                // One chunk in hand: the producer waits for the previous chunk
                // to be published before it can hand over the next.
                let (chunks, reader) = mpsc::channel(1);
                let cancel = delivery.cancel.clone();
                let writer = RawStreamWriter {
                    chunks: chunks.clone(),
                    cancel: cancel.clone(),
                    method: full_method.as_str().into(),
                };
                let work = in_turn(turn, service_name.clone(), handler(envelope.data, call, writer));
                inner.context.connection().spawn(async move {
                    let Err(error) = work.await else { return };
                    // A failure, at any point, ends the stream with a terminal
                    // error chunk, sanitised like a unary error, which the
                    // caller's iteration raises. A cancelled stream ends
                    // without one.
                    if error.kind() == ErrorKind::StreamCancelled || cancel.is_cancelled() {
                        let _ = chunks.send(Err(error)).await;
                        return;
                    }
                    if error.is_handled() {
                        log::warn!(target: "protobus", "handled error in stream {full_method}: {error}");
                    } else {
                        log::error!(target: "protobus", "error in stream {full_method}: {error}");
                    }
                    let terminal =
                        MessageFactory::build_error_response(&full_method, &sanitize_error_for_client(&error, &id));
                    let _ = chunks.send(Ok(terminal)).await;
                });
                let stream = futures_util::stream::unfold(reader, |mut reader| async move {
                    reader.recv().await.map(|chunk| (chunk, reader))
                });
                Ok(HandlerResult::Stream(Box::pin(stream)))
            }
        }
    }
}

/// Run a handler holding its service's turn, when handlers are serialized.
async fn in_turn<T>(turn: Option<Arc<tokio::sync::Mutex<()>>>, service: String, work: impl Future<Output = T>) -> T {
    match turn {
        None => work.await,
        Some(turn) => {
            SERIALIZED_SERVICE
                .scope(service, async move {
                    let _mine = turn.lock().await;
                    work.await
                })
                .await
        }
    }
}

fn last_segment(value: &str) -> &str {
    value.rsplit('.').next().unwrap_or(value)
}

fn error_reply(method: &str, error: &Error) -> HandlerResult {
    HandlerResult::Reply(MessageFactory::build_error_response(method, error))
}

/// Decode a typed request. Malformed bytes are answered as `PROTOCOL_ERROR`:
/// the same bytes fail the same way on every redelivery, so they are never
/// retried.
fn decode_request<Req: Message + prost::Name + Default>(
    factory: &MessageFactory,
    payload: &[u8],
    method: &str,
) -> Result<Req> {
    factory
        .decode::<Req>(payload)
        .map_err(|e| undecodable(payload, method, &e))
}

fn decode_dynamic_request(factory: &MessageFactory, payload: &[u8], method: &str) -> Result<DynamicMessage> {
    let input = factory.method(method)?.input();
    factory
        .decode_message(input.full_name(), payload)
        .map_err(|e| undecodable(payload, method, &e))
}

fn undecodable(payload: &[u8], method: &str, cause: &Error) -> Error {
    // Type name and size only: a payload that failed to decode is still a payload.
    log::error!(target: "protobus", "unparseable request payload for {method} ({} bytes)", payload.len());
    Error::protocol(format!(
        "payload did not decode as the request type of {method}{}",
        if cause.kind() == ErrorKind::CustomTypeRange {
            format!(": {cause}")
        } else {
            String::new()
        }
    ))
}

fn encode_dynamic_result(factory: &MessageFactory, method: &str, result: &DynamicMessage) -> Result<Vec<u8>> {
    let expected = factory.method(method)?.output();
    let actual = result.descriptor();
    if expected.full_name() != actual.full_name() {
        return Err(Error::new(
            ErrorKind::InvalidResult,
            format!(
                "{method} must return {}, not {}",
                expected.full_name(),
                actual.full_name()
            ),
        ));
    }
    factory.encode_message(result)
}

/// A handled error is expected: it is answered at once, never retried.
/// Anything else is an infrastructure failure, handed to the retry ladder with
/// the caller's (sanitised) reply pre-encoded, for the connection to send once
/// the retries are spent.
fn handle_unary_error(
    method: &str,
    error: Error,
    correlation_id: &str,
) -> std::result::Result<HandlerResult, HandlerFailure> {
    if error.is_handled() {
        log::warn!(target: "protobus", "handled error in {method}: {error}");
        return Ok(error_reply(method, &error));
    }
    log::error!(target: "protobus", "error in {method}: {error}");
    let reply = MessageFactory::build_error_response(method, &sanitize_error_for_client(&error, correlation_id));
    Err(HandlerFailure {
        error,
        reply: Some(reply),
    })
}

/// The caller's answer to a failure that reached the connection without one: a
/// processing timeout (`PROCESSING_TIMEOUT`) or a handler that panicked,
/// sanitised like any unhandled error. Sent once the retries are spent.
fn build_failure_reply(content: &[u8], error: &Error) -> Option<Vec<u8>> {
    let method = wire::decode_request(content)
        .map(|r| r.method)
        .unwrap_or_else(|_| "unknown".into());
    Some(MessageFactory::build_error_response(
        &method,
        &sanitize_error_for_client(error, ""),
    ))
}
